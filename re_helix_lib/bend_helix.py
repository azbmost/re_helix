def normalize_pivot_for_compare(token: str) -> Tuple[str, int]:
    chain_id, res_seq = parse_residue_token(token)
    return (chain_id.upper(), res_seq)


def normalize_pivots_for_compare(value: object) -> Tuple[Tuple[str, int], ...]:
    return tuple(normalize_pivot_for_compare(token) for token in parse_pivot_tokens(value))


def join_cli_values(values: object) -> Optional[str]:
    """Join the values of a repeatable option; each one may itself hold a list."""
    if values is None or isinstance(values, str):
        return values  # type: ignore[return-value]
    return ",".join(str(value) for value in values)  # type: ignore[union-attr]


def attach_negative_list_values(
    argv: Sequence[str],
    option_strings: Iterable[str],
) -> List[str]:
    """Join a value starting with ``-`` to its bend option, as in ``--phi=-30,20``.

    argparse reads ``--phi -30,20`` as an option followed by an unknown option,
    because only a bare negative number such as ``-30`` passes as a value.
    """
    options = set(option_strings)
    result: List[str] = []
    index = 0
    while index < len(argv):
        token = argv[index]
        if token == "--":
            result.extend(argv[index:])
            break
        if (
            token in options
            and index + 1 < len(argv)
            and NEGATIVE_VALUE_PATTERN.match(argv[index + 1])
        ):
            result.append(f"{token}={argv[index + 1]}")
            index += 2
            continue
        result.append(token)
        index += 1
    return result



def merge_cli_value(
    label: str,
    positional,
    optional,
    normalizer=None,
):
    if positional is not None and optional is not None:
        lhs = normalizer(positional) if normalizer is not None else positional
        rhs = normalizer(optional) if normalizer is not None else optional
        if lhs != rhs:
            raise ValueError(
                f"Conflicting values were provided for {label}: {positional!r} and {optional!r}."
            )
        return positional
    if positional is not None:
        return positional
    return optional



def resolve_run_parameters(
    args,
) -> Tuple[
    str,
    str,
    Tuple[float, ...],
    Tuple[float, ...],
    Tuple[float, ...],
    str,
    str,
    str,
    Optional[str],
    List[str],
    Tuple[float, ...],
    Tuple[float, ...],
]:
    """Merge positional and named CLI values and check them against the pivots.

    The pivots come back as one comma-joined string. Each bend value comes back
    as a tuple holding one value per pivot or a single value used at every pivot.
    """
    input_pdb = merge_cli_value(
        label="input PDB",
        positional=args.input_pdb,
        optional=args.input_pdb_opt,
        normalizer=lambda path: os.path.abspath(path),
    )
    pivot_residue = merge_cli_value(
        label="pivot residue",
        positional=args.pivot_residue,
        optional=join_cli_values(args.pivot_residue_opt),
        normalizer=normalize_pivots_for_compare,
    )
    phi_deg = merge_cli_value(
        label="phi",
        positional=args.phi_deg,
        optional=join_cli_values(args.phi_deg_opt),
        normalizer=lambda value: parse_bend_values(value, "Phi"),
    )
    beta_deg = merge_cli_value(
        label="beta",
        positional=args.beta_deg,
        optional=join_cli_values(args.beta_deg_opt),
        normalizer=lambda value: parse_bend_values(value, "Beta"),
    )
    sep_mode = normalize_sep(args.sep)
    align_mode = normalize_align(args.align)
    origin_mode = normalize_origin(args.origin)
    output_pdb = normalize_output_path(args.output_pdb)
    axis_range_specs = list(args.axis_ranges or [])

    missing = []
    if input_pdb is None:
        missing.append("input PDB")
    if pivot_residue is None:
        missing.append("pivot residue")
    if phi_deg is None:
        missing.append("phi")
    if beta_deg is None:
        missing.append("beta")

    if missing:
        raise ValueError(
            "Missing required parameter(s): "
            + ", ".join(missing)
            + ". Provide all four values positionally, with --input/--pivot/--phi/--beta, or use --gui."
        )

    pivot_tokens = parse_pivot_tokens(pivot_residue)
    values = parse_parameter_set(
        len(pivot_tokens),
        phi=phi_deg,
        beta=beta_deg,
        tau=join_cli_values(args.tau_deg_opt),
        shift_axial=join_cli_values(args.shift_axial),
        shift_radial=join_cli_values(args.shift_radial),
    )
    return (
        input_pdb,
        ",".join(pivot_tokens),
        values["phi"],
        values["beta"],
        values["tau"],
        sep_mode,
        align_mode,
        origin_mode,
        output_pdb,
        axis_range_specs,
        values["shift_axial"],
        values["shift_radial"],
    )


def run_bending(
    input_pdb: str,
    pivot_residue: object,
    phi_deg: object,
    beta_deg: object,
    tau_deg: object = 0.0,
    sep_mode: str = "n",
    align_mode: str = "y",
    origin_mode: str = "n",
    output_pdb: Optional[str] = None,
    axis_range_specs: Optional[Iterable[str]] = None,
    shift_axial: object = 0.0,
    shift_radial: object = 0.0,
    command: Optional[str] = None,
) -> Tuple[str, Dict[str, object]]:
    """Bend the input at one pivot or several, write the model, and return its info.

    ``pivot_residue`` lists the pivots in bending order, separated by spaces,
    commas, or semicolons. Each bend value is a number, list text, or sequence
    holding one value per pivot or a single value used at every pivot.
    """
    pivot_tokens = parse_pivot_tokens(pivot_residue)
    values = parse_parameter_set(
        len(pivot_tokens),
        phi=phi_deg,
        beta=beta_deg,
        tau=tau_deg,
        shift_axial=shift_axial,
        shift_radial=shift_radial,
    )
    records, residues = read_pdb(input_pdb)
    origin_source_records = clone_records(records) if origin_mode == "y" else None

    raw_axis_defs = parse_axis_range_specs(axis_range_specs)
    available_chains = []
    seen_chains = set()
    for residue in residues.values():
        if residue.p_atom is not None and residue.chain_id not in seen_chains:
            available_chains.append(residue.chain_id)
            seen_chains.add(residue.chain_id)
    axis_range_defs = resolve_axis_range_definitions(raw_axis_defs, available_chains)

    selected_keys = tuple(
        resolve_selected_key(parse_residue_token(token), residues)
        for token in pivot_tokens
    )
    out_path, info = bend_structure(
        records=records,
        residues=residues,
        input_pdb=input_pdb,
        selected_key=selected_keys,
        phi_deg=values["phi"],
        beta_deg=values["beta"],
        tau_deg=values["tau"],
        shift_axial=values["shift_axial"],
        shift_radial=values["shift_radial"],
        sep_mode=sep_mode,
        align_mode=align_mode,
        output_pdb=output_pdb,
        axis_range_defs=axis_range_defs,
    )

    if command is None:
        command = build_equivalent_cli_command(
            input_pdb=input_pdb,
            pivot_residue=",".join(pivot_tokens),
            phi_deg=values["phi"],
            beta_deg=values["beta"],
            tau_deg=values["tau"],
            sep_mode=sep_mode,
            align_mode=align_mode,
            origin_mode=origin_mode,
            output_pdb=output_pdb,
            axis_range_specs=[
                format_axis_range_spec(axis_def) for axis_def in axis_range_defs
            ],
            shift_axial=values["shift_axial"],
            shift_radial=values["shift_radial"],
        )
    remark_lines = build_bend_remark_lines(command)
    write_pdb(
        insert_remark_records(records, remark_lines),
        out_path,
        update_ter=(sep_mode == "y"),
    )
    info["command"] = command
    info["remark_lines"] = tuple(remark_lines)

    info["origin_mode"] = origin_mode
    info["origin_out_path"] = None
    info["origin_chain_map_model1"] = None
    info["origin_chain_map_model2"] = None
    info["origin_chain_maps"] = None
    info["axis_range_specs"] = [format_axis_range_spec(axis_def) for axis_def in axis_range_defs]

    if origin_mode == "y":
        if origin_source_records is None:
            raise ValueError("Internal error: missing source records for --origin output.")
        origin_out_path = make_origin_output_name(out_path)
        sequence = info["bend_sequence"]
        origin_info = write_origin_overlay_pdb(
            records=origin_source_records,
            out_path=origin_out_path,
            # One full generated helix per bend, after the input helix.
            transform_coord=[
                lambda coord, helix_index=helix_index: sequence.helix_coord(
                    helix_index, coord
                )
                for helix_index in range(1, len(sequence.transforms) + 1)
            ],
            chain_order=list(info["duplex_chains"]),
            remark_lines=remark_lines,
        )
        info["origin_out_path"] = origin_out_path
        info.update(origin_info)

    return out_path, info


def write_additional_screening_solution_outputs(
    result: ScreeningResult,
    input_pdb: str,
    pivot_residue: str,
    sep_mode: str,
    align_mode: str,
    axis_range_specs: Optional[Iterable[str]] = None,
    explicit_primary_output: Optional[str] = None,
    pivot: object = None,
) -> Tuple[Tuple[str, Optional[str]], ...]:
    """Write every reported solution after the primary/best one, including overlays."""
    written = []
    # Fall back to the caller's own token so these names carry the same pivot
    # block that bend_structure puts on the primary output.
    pivot_label = pivot if pivot is not None else pivot_residue
    for solution_index, solution in enumerate(result.solutions[1:], start=2):
        solution_out_path = make_screen_solution_output_name(
            input_pdb=input_pdb,
            solution=solution,
            solution_index=solution_index,
            sep_mode=sep_mode,
            explicit_primary_output=explicit_primary_output,
            pivot=pivot_label,
        )
        written_path, solution_info = run_bending(
            input_pdb=input_pdb,
            pivot_residue=pivot_residue,
            phi_deg=solution.phi_deg,
            beta_deg=solution.beta_deg,
            tau_deg=solution.tau_deg,
            shift_axial=solution.shift_axial,
            shift_radial=solution.shift_radial,
            sep_mode=sep_mode,
            align_mode=align_mode,
            origin_mode="y",
            output_pdb=solution_out_path,
            axis_range_specs=axis_range_specs,
        )
        written.append((written_path, solution_info.get("origin_out_path")))
    return tuple(written)


def _xyz_text(vector: Sequence[float], digits: int) -> str:
    return "(" + ", ".join(f"{float(value):.{digits}f}" for value in vector) + ")"


def _format_multi_pivot_summary(out_path: str, info: Dict[str, object]) -> str:
    """Describe every piece and every bend of a multi-pivot run."""
    bends: Sequence[Dict[str, object]] = info["bends"]
    pieces: Sequence[Dict[str, object]] = info["pieces"]
    n_pairs = info["n_pairs"]
    pivot_text = ", ".join(_residue_label(bend["pivot"]) for bend in bends)
    lines = [
        f"Wrote {out_path}",
        (
            f"Bent at {len(bends)} pivots in the listed order: {pivot_text}. Each bend "
            "acts on the full helix the previous bend generated, and the output links "
            "one piece from each helix."
        ),
    ]
    for piece in pieces:
        source = (
            "input helix"
            if piece["pivot"] is None
            else (
                f"helix generated by bend {piece['helix']} at "
                f"{_residue_label(piece['pivot'])}"
            )
        )
        lines.append(
            f"Piece #{piece['piece']} is {'fixed' if piece['pivot'] is None else 'movable'}: "
            f"base-pair range {piece['pair_start']}..{piece['pair_end']} of {n_pairs} "
            f"in axial order ({source})"
        )
    for bend in bends:
        pair_a, pair_b = bend["pair"]
        lines.extend(
            [
                f"Bend {bend['bend_index']} at pivot {_residue_label(bend['pivot'])}:",
                f"  Split base pair / pivot border: {pair_a[0]}{pair_a[1]} / {pair_b[0]}{pair_b[1]}",
                f"  Axis source: {bend.get('axis_source') or 'automatic whole-duplex axis'}",
                f"  Estimated helix radius at pivot P: {float(bend['radius']):.3f} A",
                f"  Axis direction: {_xyz_text(bend['axis_dir'], 6)}",
                (
                    f"  Phi {float(bend['phi_deg']):.6f} deg, beta "
                    f"{float(bend['beta_deg']):.6f} deg, tau "
                    f"{float(bend['tau_deg']):.6f} deg"
                ),
                (
                    "  Pivot shift before bending: axial "
                    f"{float(bend['shift_axial']):.6f} A, radial "
                    f"{float(bend['shift_radial']):.6f} A"
                ),
            ]
        )
        if bend["shift_vector"] != (0.0, 0.0, 0.0):
            lines.extend(
                [
                    f"  Pivot shift translation: {_xyz_text(bend['shift_vector'], 3)}",
                    f"  Shifted pivot P position: {_xyz_text(bend['pivot_shifted'], 3)}",
                    f"  Shifted helix radius at pivot P: {float(bend['shifted_radius']):.3f} A",
                ]
            )
        lines.extend(
            [
                f"  Hinge point: {_xyz_text(bend['hinge_point'], 3)}",
                f"  Hinge direction: {_xyz_text(bend['hinge_dir'], 6)}",
                f"  Twist axis point: {_xyz_text(bend['twist_axis_point'], 3)}",
                f"  Twist axis direction: {_xyz_text(bend['twist_axis_dir'], 6)}",
            ]
        )
        if bend.get("align_mode") == "y":
            lines.append(
                f"  Alignment translation: {_xyz_text(bend['align_translation'], 3)}"
            )
    lines.append(
        "Align each pivot P back to its shifted pivot position (--align): "
        f"{info['align_mode']}"
    )

    if info.get("sep_mode") == "y":
        mapping_text = "; ".join(
            f"piece #{piece['piece']} "
            + ", ".join(f"{old}->{new}" for old, new in piece["chain_map"].items())
            for piece in pieces
            if piece["chain_map"]
        )
        lines.append(f"Separated piece chain IDs: {mapping_text}")

    if info.get("origin_mode") == "y":
        lines.append(f"Origin comparison PDB (--origin): {info['origin_out_path']}")
        chain_maps = info.get("origin_chain_maps") or ()
        duplex_chains = info.get("duplex_chains") or ()
        if chain_maps and duplex_chains:
            model_texts = []
            for model_index, chain_map in enumerate(chain_maps):
                ids = ", ".join(chain_map[cid] for cid in duplex_chains if cid in chain_map)
                source = "input helix" if model_index == 0 else f"bend {model_index}"
                model_texts.append(f"model {model_index + 1} [{ids}] ({source})")
            lines.append("Origin full-helix chain IDs: " + ", ".join(model_texts))

    return "\n".join(lines)


def format_run_summary(out_path: str, info: Dict[str, object]) -> str:
    if len(info.get("bends") or ()) > 1:
        return _format_multi_pivot_summary(out_path, info)
    pair_a, pair_b = info["pair"]
    axis_dir = info["axis_dir"]
    hinge_point = info["hinge_point"]
    hinge_dir = info["hinge_dir"]
    twist_axis_point = info["twist_axis_point"]
    twist_axis_dir = info["twist_axis_dir"]
    align_translation = info["align_translation"]
    piece1_end = int(info["piece2_pair_start"]) - 1
    shift_vector = info.get("shift_vector") or (0.0, 0.0, 0.0)
    pivot_shifted = info.get("pivot_shifted")

    shift_detail_lines: List[str] = []
    if shift_vector != (0.0, 0.0, 0.0):
        shift_detail_lines.append(
            "Pivot shift translation applied to movable piece #2: "
            f"({shift_vector[0]:.3f}, {shift_vector[1]:.3f}, {shift_vector[2]:.3f})"
        )
        if pivot_shifted is not None:
            shift_detail_lines.append(
                "Shifted pivot P position: "
                f"({pivot_shifted[0]:.3f}, {pivot_shifted[1]:.3f}, {pivot_shifted[2]:.3f})"
            )
        shift_detail_lines.append(
            "Shifted helix radius at pivot P: "
            f"{float(info.get('shifted_radius', info['radius'])):.3f} A"
        )

    lines = [
        f"Wrote {out_path}",
        f"Split base pair / pivot border: {pair_a[0]}{pair_a[1]} / {pair_b[0]}{pair_b[1]}",
        f"Piece #1 is fixed: base-pair range 1..{piece1_end} of {info['n_pairs']} in axial order",
        (
            "Piece #2 is movable: base-pair range "
            f"{info['piece2_pair_start']}..{info['piece2_pair_end']} of {info['n_pairs']} in axial order"
        ),
        f"Axis source: {info.get('axis_source') or 'automatic whole-duplex axis'}",
        f"Estimated helix radius at pivot P: {info['radius']:.3f} A",
        f"Axis direction: ({axis_dir[0]:.6f}, {axis_dir[1]:.6f}, {axis_dir[2]:.6f})",
        (
            "Pivot shift of movable piece #2 before bending: axial "
            f"{float(info.get('shift_axial', 0.0)):.6f} A, radial "
            f"{float(info.get('shift_radial', 0.0)):.6f} A"
        ),
        *shift_detail_lines,
        f"Hinge point: ({hinge_point[0]:.3f}, {hinge_point[1]:.3f}, {hinge_point[2]:.3f})",
        f"Hinge direction: ({hinge_dir[0]:.6f}, {hinge_dir[1]:.6f}, {hinge_dir[2]:.6f})",
        f"Tau twist of movable piece #2: {info['tau_deg']:.6f} deg",
        f"Twist axis point: ({twist_axis_point[0]:.3f}, {twist_axis_point[1]:.3f}, {twist_axis_point[2]:.3f})",
        f"Twist axis direction: ({twist_axis_dir[0]:.6f}, {twist_axis_dir[1]:.6f}, {twist_axis_dir[2]:.6f})",
        f"Align pivot P back to its shifted pivot position (--align): {info['align_mode']}",
    ]

    if info.get("align_mode") == "y":
        lines.append(
            "Alignment translation applied to movable piece #2: "
            f"({align_translation[0]:.3f}, {align_translation[1]:.3f}, {align_translation[2]:.3f})"
        )

    if info.get("sep_mode") == "y":
        chain_map = info.get("piece2_chain_map") or {}
        mapping_text = ", ".join(f"{old}->{new}" for old, new in chain_map.items())
        lines.append(f"Separated piece #2 chain IDs: {mapping_text}")

    if info.get("origin_mode") == "y":
        lines.append(f"Origin comparison PDB (--origin): {info['origin_out_path']}")
        chain_map_model1 = info.get("origin_chain_map_model1") or {}
        chain_map_model2 = info.get("origin_chain_map_model2") or {}
        duplex_chains = info.get("duplex_chains") or ()
        if chain_map_model1 and chain_map_model2 and duplex_chains:
            model1_ids = ", ".join(chain_map_model1[cid] for cid in duplex_chains if cid in chain_map_model1)
            model2_ids = ", ".join(chain_map_model2[cid] for cid in duplex_chains if cid in chain_map_model2)
            lines.append(f"Origin full-helix chain IDs: model 1 [{model1_ids}], model 2 [{model2_ids}]")

    return "\n".join(lines)


