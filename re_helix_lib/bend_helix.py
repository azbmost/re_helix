    def overlay_mapping_summary() -> str:
        input_pdb = input_var.get().strip()
        if not input_pdb:
            return "Choose an input PDB to display its origin-overlay chain mapping."
        try:
            _records, residues = read_pdb(input_pdb)
            chains: List[str] = []
            for residue in residues.values():
                if residue.p_atom is not None and residue.chain_id not in chains:
                    chains.append(residue.chain_id)
            if len(chains) != 2:
                return f"The selected PDB has {len(chains)} P-containing chains; Bend Helix requires 2."
            pivots = split_list_text(pivot_var.get())
            model_maps = build_origin_overlay_model_maps(chains, max(len(pivots), 1) + 1)

            def mapping_text(chain_map: Dict[str, str]) -> str:
                return ", ".join(
                    f"{overlay} ← input {source}" for source, overlay in chain_map.items()
                )

            if len(pivots) <= 1:
                return (
                    f"Origin overlay: original model [{mapping_text(model_maps[0])}]; "
                    f"transformed model [{mapping_text(model_maps[1])}]."
                )
            generated = "; ".join(
                f"helix from bend {index} at {pivot} [{mapping_text(chain_map)}]"
                for index, (pivot, chain_map) in enumerate(
                    zip(pivots, model_maps[1:]), start=1
                )
            )
            return (
                f"Origin overlay: input helix [{mapping_text(model_maps[0])}]; "
                f"{generated}. Screened values apply at every pivot."
            )
        except Exception as exc:
            return f"Origin-overlay mapping is unavailable: {exc}"

    def screening_block_reason() -> str:
        """Explain why screening is off, or return "" when it is available."""
        listed = [
            SCREEN_VARIABLE_LABELS[name]
            for name in SCREEN_VARIABLE_NAMES
            if len(split_list_text(variable_vars[name].get())) > 1
        ]
        if not listed:
            return ""
        return (
            "Screening is off: "
            + ", ".join(listed)
            + (" has" if len(listed) == 1 else " have")
            + " more than one value. Give every parameter a single value to screen."
        )

