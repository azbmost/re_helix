def format_angle_for_filename(value: float) -> str:
    if abs(value - round(value)) < 1.0e-8:
        s = str(int(round(value)))
    else:
        s = f"{value:.3f}".rstrip("0").rstrip(".")
    s = s.replace("-", "m").replace(".", "p")
    return s



def format_pivot_for_filename(pivot: object) -> str:
    """Return the pivot residue as a filename-safe ``A36`` style label.

    Accepts a resolved ``(chain_id, res_seq)`` key or any residue token the CLI
    takes, so callers holding either form produce the same label.
    """
    if isinstance(pivot, (tuple, list)) and len(pivot) == 2:
        chain_id, res_seq = pivot[0], int(pivot[1])
    else:
        chain_id, res_seq = parse_residue_token(str(pivot))
    chain = str(chain_id).strip() or "_"
    return f"{chain}{format_angle_for_filename(res_seq)}"


def _is_residue_key(value: object) -> bool:
    """Tell a resolved ``(chain_id, res_seq)`` key from a sequence of pivots."""
    return (
        isinstance(value, (tuple, list))
        and len(value) == 2
        and isinstance(value[0], str)
        and len(value[0]) <= 1
        and not isinstance(value[1], (tuple, list, bool))
    )


def pivot_filename_labels(pivot: object) -> Tuple[str, ...]:
    """Return filename labels for one pivot or several, in bending order.

    A resolved key or a residue token names one pivot; list text such as
    ``"A20,A40"`` or a sequence of keys or tokens names several.
    """
    if pivot is None:
        return ()
    if isinstance(pivot, str):
        return tuple(
            format_pivot_for_filename(token) for token in parse_pivot_tokens(pivot)
        )
    if _is_residue_key(pivot):
        return (format_pivot_for_filename(pivot),)
    return tuple(format_pivot_for_filename(item) for item in pivot)  # type: ignore[union-attr]


def format_float_for_cli(value: float) -> str:
    if abs(value - round(value)) < 1.0e-8:
        return str(int(round(value)))
    return f"{value:.15g}"


def build_equivalent_cli_command(
    input_pdb: str,
    pivot_residue: object,
    phi_deg: object,
    beta_deg: object,
    tau_deg: object,
    sep_mode: str,
    align_mode: str,
    origin_mode: str,
    output_pdb: Optional[str] = None,
    axis_range_specs: Optional[Iterable[str]] = None,
    shift_axial: object = 0.0,
    shift_radial: object = 0.0,
) -> str:
    """Rebuild the CLI command for a run.

    Each bend value may be one number or a sequence: a single value is written
    as before, and per-pivot values as a comma list such as ``--beta 30,20``.
    """
    script_name = os.path.basename(__file__) if "__file__" in globals() else "bend_helixV2_6.py"
    parts = [
        "python",
        script_name,
        "--input",
        input_pdb,
        "--pivot",
        ",".join(parse_pivot_tokens(pivot_residue)),
    ]
    for flag, value in (
        ("--phi", phi_deg),
        ("--beta", beta_deg),
        ("--tau", 0.0 if tau_deg is None else tau_deg),
        ("--shift_axial", 0.0 if shift_axial is None else shift_axial),
        ("--shift_radial", 0.0 if shift_radial is None else shift_radial),
    ):
        values = parse_bend_values(value, flag)
        text = ",".join(format_float_for_cli(item) for item in values)
        if len(values) > 1 and NEGATIVE_VALUE_PATTERN.match(text):
            # argparse reads a bare "-30,20" as an option, so attach it.
            parts.append(f"{flag}={text}")
        else:
            parts.extend([flag, text])
    parts.extend(["--sep", sep_mode, "--align", align_mode, "--origin", origin_mode])
    if output_pdb:
        parts.extend(["-o", output_pdb])
    for spec in axis_range_specs or []:
        spec = str(spec).strip()
        if spec:
            parts.extend(["--axis_range", spec])
    return " ".join(shlex.quote(part) for part in parts)


def _bend_value_block(
    phi_deg: float,
    beta_deg: float,
    tau_deg: float,
    shift_axial: float = 0.0,
    shift_radial: float = 0.0,
) -> str:
    block = (
        f"P{format_angle_for_filename(phi_deg)}"
        f"B{format_angle_for_filename(beta_deg)}"
        f"T{format_angle_for_filename(tau_deg)}"
    )
    # Unshifted bends keep the historical PxByTz block untouched.
    if float(shift_axial) != 0.0 or float(shift_radial) != 0.0:
        block += (
            f"Sa{format_angle_for_filename(shift_axial)}"
            f"Sr{format_angle_for_filename(shift_radial)}"
        )
    return block


def _finish_output_name(
    stem: str,
    body: str,
    ext: str,
    sep_mode: str,
    screen_mode: bool,
    pivot_labels: Sequence[str],
) -> str:
    tail = ("_scr" if screen_mode else "") + ("_sep" if sep_mode == "y" else "")
    name = f"{stem}_{body}{tail}{ext}"
    # Many pivots can outgrow the filename limit; the COMMAND remark keeps the
    # full recipe, so a first-to-last pivot label plus a digest is enough.
    if (
        len(pivot_labels) > 1
        and len(os.path.basename(name).encode("utf-8")) > MAX_AUTOMATIC_NAME_BYTES
    ):
        digest = hashlib.sha1(body.encode("utf-8")).hexdigest()[:10]
        name = (
            f"{stem}_Pv{pivot_labels[0]}-{pivot_labels[-1]}x{len(pivot_labels)}"
            f"_{digest}{tail}{ext}"
        )
    return name


def make_output_name(
    inp: str,
    phi_deg: float,
    beta_deg: float,
    tau_deg: float,
    shift_axial: float = 0.0,
    shift_radial: float = 0.0,
    sep_mode: str = "n",
    screen_mode: bool = False,
    pivot: object = None,
) -> str:
    """Name a bend whose values are shared by every pivot.

    Several pivots are listed in bending order ahead of the one shared value
    block, for example ``model_PvA20PvA40_P0B30T0.pdb``.
    """
    stem, ext = os.path.splitext(inp)
    if not ext:
        ext = ".pdb"
    labels = pivot_filename_labels(pivot)
    pivot_block = "".join(f"Pv{label}" for label in labels)
    body = (f"{pivot_block}_" if pivot_block else "") + _bend_value_block(
        phi_deg, beta_deg, tau_deg, shift_axial, shift_radial
    )
    return _finish_output_name(stem, body, ext, sep_mode, screen_mode, labels)


def make_bend_output_name(
    inp: str,
    pivots: object,
    phi_values: Sequence[float],
    beta_values: Sequence[float],
    tau_values: Sequence[float] = (0.0,),
    shift_axial_values: Sequence[float] = (0.0,),
    shift_radial_values: Sequence[float] = (0.0,),
    sep_mode: str = "n",
    screen_mode: bool = False,
) -> str:
    """Name a bend whose values were each given once or once per pivot.

    When every value is shared this is ``make_output_name``; otherwise each
    pivot carries its own value block, for example
    ``model_PvA20_P0B30T0_PvA40_P90B20T0.pdb``.
    """
    value_lists = [
        tuple(values)
        for values in (
            phi_values,
            beta_values,
            tau_values,
            shift_axial_values,
            shift_radial_values,
        )
    ]
    if all(len(values) == 1 for values in value_lists):
        return make_output_name(
            inp,
            *(values[0] for values in value_lists),
            sep_mode=sep_mode,
            screen_mode=screen_mode,
            pivot=pivots,
        )
    labels = pivot_filename_labels(pivots)
    if not labels:
        raise ValueError("Per-pivot bend values need the pivots they belong to.")
    stem, ext = os.path.splitext(inp)
    if not ext:
        ext = ".pdb"
    per_pivot = [expand_bend_values(values, len(labels)) for values in value_lists]
    body = "_".join(
        f"Pv{label}_{_bend_value_block(*(values[index] for values in per_pivot))}"
        for index, label in enumerate(labels)
    )
    return _finish_output_name(stem, body, ext, sep_mode, screen_mode, labels)



def make_origin_output_name(main_out_path: str) -> str:
    stem, ext = os.path.splitext(main_out_path)
    if not ext:
        ext = ".pdb"
    return f"{stem}-ori{ext}"


def make_screen_solution_output_name(
    input_pdb: str,
    solution: ScreeningSolution,
    solution_index: int,
    sep_mode: str = "n",
    explicit_primary_output: Optional[str] = None,
    pivot: object = None,
) -> str:
    """Name one additional reported screening solution deterministically."""
    if solution_index < 2:
        raise ValueError("Additional screening solution indexes must start at 2.")
    if explicit_primary_output is not None:
        primary = normalize_output_path(explicit_primary_output)
        if primary is None:
            raise ValueError("Explicit primary screening output cannot be blank.")
        stem, ext = os.path.splitext(primary)
        return f"{stem}_sol{solution_index:03d}{ext}"

    generated = make_output_name(
        input_pdb,
        solution.phi_deg,
        solution.beta_deg,
        solution.tau_deg,
        solution.shift_axial,
        solution.shift_radial,
        sep_mode=sep_mode,
        screen_mode=True,
        pivot=pivot,
    )
    stem, ext = os.path.splitext(generated)
    if stem.endswith("_sep"):
        stem = stem[:-4] + f"_sol{solution_index:03d}_sep"
    else:
        stem += f"_sol{solution_index:03d}"
    return stem + ext


def normalize_output_path(output_pdb: Optional[str]) -> Optional[str]:
    if output_pdb is None:
        return None
    out = output_pdb.strip()
    if not out:
        return None
    stem, ext = os.path.splitext(out)
    if not ext:
        out = stem + ".pdb"
    return out


