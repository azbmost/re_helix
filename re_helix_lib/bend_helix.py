def find_pair_index(pairs: List[Tuple[Residue, Residue]], target_key: Tuple[str, int]) -> int:
    for i, (r1, r2) in enumerate(pairs):
        if (r1.chain_id, r1.res_seq) == target_key or (r2.chain_id, r2.res_seq) == target_key:
            return i
    raise ValueError(
        f"Selected residue {target_key[0]}{target_key[1]} is not part of the paired duplex axis model."
    )



def choose_new_chain_ids(
    existing_chain_ids: List[str],
    n_needed: int,
    purpose: str = "separated piece 2",
) -> List[str]:
    used = set(existing_chain_ids)
    available = [cid for cid in CHAIN_ID_CANDIDATES if cid not in used]
    if len(available) < n_needed:
        raise ValueError(
            f"Unable to assign new chain IDs for {purpose}: "
            f"need {n_needed}, but only {len(available)} unused one-character IDs are available."
        )
    return available[:n_needed]



def separate_piece_chains(
    records,
    piece_key_sets: Sequence[Iterable[Tuple[str, int]]],
    duplex_chains: Sequence[str],
) -> List[Dict[str, str]]:
    """Give every movable piece its own new chain IDs, in piece order."""
    existing_chain_ids = []
    seen_existing = set()
    for rec in records:
        if isinstance(rec, AtomRecord) and rec.chain_id not in seen_existing:
            existing_chain_ids.append(rec.chain_id)
            seen_existing.add(rec.chain_id)

    chains = list(duplex_chains)
    new_chain_ids = choose_new_chain_ids(
        existing_chain_ids,
        len(chains) * len(piece_key_sets),
        purpose=(
            "separated piece 2"
            if len(piece_key_sets) == 1
            else "the separated movable pieces"
        ),
    )
    chain_maps: List[Dict[str, str]] = []
    map_for_key: Dict[Tuple[str, int], Dict[str, str]] = {}
    for piece_index, keys in enumerate(piece_key_sets):
        ids = new_chain_ids[piece_index * len(chains):(piece_index + 1) * len(chains)]
        chain_map = {old: new for old, new in zip(chains, ids)}
        chain_maps.append(chain_map)
        for key in keys:
            map_for_key[key] = chain_map

    for rec in records:
        if isinstance(rec, AtomRecord):
            chain_map = map_for_key.get((rec.chain_id, rec.res_seq))
            if chain_map is not None:
                rec.set_chain_id(chain_map[rec.chain_id])

    return chain_maps


def prepare_bend_geometry(
    residues: "OrderedDict[Tuple[str, int], Residue]",
    selected_key: Tuple[str, int],
    axis_range_defs: Optional[List[AxisRangeDefinition]] = None,
) -> BendGeometryPreparation:
    """Prepare pivot, duplex, and local-axis geometry without changing atoms."""
    duplex = build_duplex_data(
        residues, selected_key=selected_key, axis_range_defs=axis_range_defs
    )
    pairs = duplex["pairs"]

    if selected_key not in residues:
        raise ValueError(
            f"Residue {selected_key[0]}{selected_key[1]} was not found in the input PDB."
        )
    if residues[selected_key].p_atom is None:
        raise ValueError(
            f"Residue {selected_key[0]}{selected_key[1]} does not contain a P atom."
        )

    pair_idx = find_pair_index(pairs, selected_key)
    pair_keys = tuple(
        (
            (first.chain_id, first.res_seq),
            (second.chain_id, second.res_seq),
        )
        for first, second in pairs
    )
    piece2_keys = frozenset(
        key for pair in pair_keys[pair_idx:] for key in pair
    )

    axis_point = duplex["axis_point"]
    axis_dir = duplex["axis_dir"]
    selected_p = residues[selected_key].p_coord()
    axis_foot = project_point_to_line(selected_p, axis_point, axis_dir)
    radial = v_sub(selected_p, axis_foot)
    radius = v_len(radial)
    if radius < EPS:
        raise ValueError(
            f"Selected P atom at {selected_key[0]}{selected_key[1]} lies too close "
            "to the estimated helix axis."
        )

    axis_range_used = duplex.get("axis_range_used")
    return BendGeometryPreparation(
        selected_key=selected_key,
        selected_p=selected_p,
        axis_point=axis_point,
        axis_dir=axis_dir,
        axis_foot=axis_foot,
        radial=radial,
        radial_dir=v_norm(radial),
        radius=radius,
        pair_idx=pair_idx,
        pair_keys=pair_keys,
        piece2_keys=piece2_keys,
        duplex_chains=tuple(duplex["chains"]),
        axis_source=str(duplex.get("axis_source") or "automatic whole-duplex axis"),
        axis_range_used=(
            format_axis_range_spec(axis_range_used)
            if axis_range_used is not None
            else None
        ),
    )


def build_bend_transform(
    preparation: BendGeometryPreparation,
    phi_deg: float,
    beta_deg: float,
    tau_deg: float = 0.0,
    shift_axial: float = 0.0,
    shift_radial: float = 0.0,
    align_mode: str = "y",
) -> BendTransform:
    """Build one candidate's full-helix transform without mutating records."""
    phi_deg = float(phi_deg)
    beta_deg = float(beta_deg)
    tau_deg = float(tau_deg)
    shift_axial = float(shift_axial)
    shift_radial = float(shift_radial)
    if not math.isfinite(shift_axial):
        raise ValueError("Axial pivot shift must be finite.")
    if not math.isfinite(shift_radial):
        raise ValueError("Radial pivot shift must be finite.")
    align_mode = normalize_align(align_mode)

    phi_rad = math.radians(phi_deg)
    beta_rad = math.radians(beta_deg)
    tau_rad = math.radians(tau_deg)

    # Translate movable piece #2 first, then rebuild every rotation from the
    # shifted pivot. Both offsets are exactly zero-preserving, so a zero shift
    # reproduces the pre-V2.7 geometry bit for bit.
    shift_vector = v_add(
        v_scale(preparation.axis_dir, shift_axial),
        v_scale(preparation.radial_dir, shift_radial),
    )
    pivot_shifted = v_add(preparation.selected_p, shift_vector)
    axis_foot_shifted = v_add(
        preparation.axis_foot, v_scale(preparation.axis_dir, shift_axial)
    )
    radial_shifted = v_add(
        preparation.radial, v_scale(preparation.radial_dir, shift_radial)
    )
    shifted_radius = preparation.radius + shift_radial

    radial_phi = rotate_vector(radial_shifted, preparation.axis_dir, phi_rad)
    hinge_point = v_add(axis_foot_shifted, radial_phi)
    # The radial vector is perpendicular to the unit axis, so
    # |axis_dir x radial_phi| == |shifted_radius|. A radial shift may pull the
    # hinge onto the axis or past it, where that tangent is either degenerate or
    # sign-flipped; deriving it from the unit radial direction instead keeps the
    # hinge direction, and therefore the sense of beta, continuous across the
    # crossing. The threshold sits far below any physical helix radius, so an
    # unshifted run always takes the first branch.
    tangent_source = (
        radial_phi
        if shifted_radius >= HINGE_TANGENT_MIN_RADIUS
        else rotate_vector(preparation.radial_dir, preparation.axis_dir, phi_rad)
    )
    hinge_dir = v_cross(preparation.axis_dir, tangent_source)
    if v_len(hinge_dir) < EPS:
        raise ValueError("Failed to construct a non-zero tangent direction for the hinge.")
    hinge_dir = v_norm(hinge_dir)

    # tau spins piece #2 about its own helical axis, which the shift carries
    # along with the piece.
    twist_axis_point_pre_align = rotate_point_about_line(
        v_add(preparation.axis_foot, shift_vector), hinge_point, hinge_dir, beta_rad
    )
    twist_axis_dir = v_norm(
        rotate_vector(preparation.axis_dir, hinge_dir, beta_rad)
    )

    def transform_without_alignment(coord: Point3D) -> Point3D:
        transformed = rotate_point_about_line(
            v_add(coord, shift_vector), hinge_point, hinge_dir, beta_rad
        )
        if abs(tau_rad) > 0.0:
            transformed = rotate_point_about_line(
                transformed,
                twist_axis_point_pre_align,
                twist_axis_dir,
                tau_rad,
            )
        return transformed

    align_translation: Point3D = (0.0, 0.0, 0.0)
    if align_mode == "y":
        align_translation = v_sub(
            pivot_shifted,
            transform_without_alignment(preparation.selected_p),
        )

    return BendTransform(
        phi_deg=phi_deg,
        beta_deg=beta_deg,
        tau_deg=tau_deg,
        shift_axial=shift_axial,
        shift_radial=shift_radial,
        shift_vector=shift_vector,
        pivot_shifted=pivot_shifted,
        shifted_radius=shifted_radius,
        hinge_point=hinge_point,
        hinge_dir=hinge_dir,
        twist_axis_point_pre_align=twist_axis_point_pre_align,
        twist_axis_point=v_add(twist_axis_point_pre_align, align_translation),
        twist_axis_dir=twist_axis_dir,
        align_mode=align_mode,
        align_translation=align_translation,
    )


def _selected_key_tuple(selected_key: object) -> Tuple[Tuple[str, int], ...]:
    """Accept one resolved pivot key or a sequence of them, in bending order."""
    if _is_residue_key(selected_key):
        return (selected_key,)  # type: ignore[return-value]
    return tuple(selected_key)  # type: ignore[arg-type]


