def prepare_bend_pivots(
    residues: "OrderedDict[Tuple[str, int], Residue]",
    selected_keys: object,
    axis_range_defs: Optional[List[AxisRangeDefinition]] = None,
) -> Tuple[BendGeometryPreparation, ...]:
    """Prepare every pivot's frame on the input helix and check that they chain.

    Bend k acts on the full helix that bend k - 1 generated, so pivot k must lie
    in the movable piece of bend k - 1: strictly after pivot k - 1 in the
    base-pair order that every pivot shares.
    """
    keys = _selected_key_tuple(selected_keys)
    if not keys:
        raise ValueError("Please provide at least one pivot P residue.")
    preparations = tuple(
        prepare_bend_geometry(residues, key, axis_range_defs=axis_range_defs)
        for key in keys
    )
    first = preparations[0]
    pair_count = len(first.pair_keys)
    for previous, current in zip(preparations, preparations[1:]):
        current_label = _residue_label(current.selected_key)
        previous_label = _residue_label(previous.selected_key)
        if current.pair_keys != first.pair_keys:
            raise ValueError(
                f"Pivots {_residue_label(first.selected_key)} and {current_label} use "
                "local axes that order the base pairs differently, so their pieces "
                "cannot be chained. Give every axis range the same start-to-end "
                "direction along the helix."
            )
        if current.pair_idx == previous.pair_idx:
            raise ValueError(
                f"Pivots {previous_label} and {current_label} mark the same base-pair "
                f"border (base pair {current.pair_idx + 1} of {pair_count}); give each "
                "border only once."
            )
        if current.pair_idx < previous.pair_idx:
            raise ValueError(
                f"Pivot {current_label} (base pair {current.pair_idx + 1} of "
                f"{pair_count}) does not fall on the helix generated by the previous "
                f"bend at {previous_label} (base pair {previous.pair_idx + 1}). Each "
                "pivot must lie in the movable piece of the bend before it, after "
                f"{previous_label} along the helix axis, so list the pivots in order "
                "along the helix."
            )
    return preparations


def carry_bend_preparation(
    preparation: BendGeometryPreparation,
    transforms: Sequence[BendTransform],
) -> BendGeometryPreparation:
    """Return a pivot frame as it sits on the helix the given bends generated.

    A generated helix is a rigid copy of the input, so carrying the input frame
    through the bends gives the frame Bend Helix would estimate on that helix
    itself, without re-fitting an axis to moved atoms.
    """
    if not transforms:
        return preparation

    def carry_point(point: Point3D) -> Point3D:
        for transform in transforms:
            point = transform.transform_coord(point)
        return point

    def carry_vector(vector: Point3D) -> Point3D:
        for transform in transforms:
            vector = transform.transform_vector(vector)
        return vector

    return replace(
        preparation,
        selected_p=carry_point(preparation.selected_p),
        axis_point=carry_point(preparation.axis_point),
        axis_dir=v_norm(carry_vector(preparation.axis_dir)),
        axis_foot=carry_point(preparation.axis_foot),
        radial=carry_vector(preparation.radial),
        radial_dir=v_norm(carry_vector(preparation.radial_dir)),
    )


def build_bend_sequence(
    preparations: Sequence[BendGeometryPreparation],
    phi_values: Sequence[float],
    beta_values: Sequence[float],
    tau_values: Sequence[float] = (0.0,),
    shift_axial_values: Sequence[float] = (0.0,),
    shift_radial_values: Sequence[float] = (0.0,),
    align_mode: str = "y",
) -> BendSequence:
    """Build every bend in pivot order, each on the helix the previous one generated.

    Each value sequence holds one value per pivot or one value shared by all.
    ``prepare_bend_pivots`` puts pivot k after every earlier pivot, so every
    earlier bend has moved it and its frame is carried through all of them.
    """
    preparations = tuple(preparations)
    count = len(preparations)
    phis = expand_bend_values(phi_values, count)
    betas = expand_bend_values(beta_values, count)
    taus = expand_bend_values(tau_values, count)
    shifts_axial = expand_bend_values(shift_axial_values, count)
    shifts_radial = expand_bend_values(shift_radial_values, count)
    carried_preparations: List[BendGeometryPreparation] = []
    transforms: List[BendTransform] = []
    for index, preparation in enumerate(preparations):
        carried = carry_bend_preparation(preparation, transforms)
        transforms.append(
            build_bend_transform(
                carried,
                phi_deg=phis[index],
                beta_deg=betas[index],
                tau_deg=taus[index],
                shift_axial=shifts_axial[index],
                shift_radial=shifts_radial[index],
                align_mode=align_mode,
            )
        )
        carried_preparations.append(carried)
    return BendSequence(tuple(carried_preparations), tuple(transforms))


def _bend_step_info(
    index: int,
    preparation: BendGeometryPreparation,
    carried: BendGeometryPreparation,
    transform: BendTransform,
) -> Dict[str, object]:
    """Describe one bend: its pivot, its frame on the helix it acts on, its transform."""
    return {
        "bend_index": index + 1,
        "pivot": preparation.selected_key,
        "pair_idx": preparation.pair_idx,
        "pair": preparation.pair_keys[preparation.pair_idx],
        "radius": preparation.radius,
        "axis_point": carried.axis_point,
        "axis_dir": carried.axis_dir,
        "selected_p": carried.selected_p,
        "radial_dir": carried.radial_dir,
        "axis_source": preparation.axis_source,
        "axis_range_used": preparation.axis_range_used,
        "hinge_point": transform.hinge_point,
        "hinge_dir": transform.hinge_dir,
        "phi_deg": transform.phi_deg,
        "beta_deg": transform.beta_deg,
        "tau_deg": transform.tau_deg,
        "shift_axial": transform.shift_axial,
        "shift_radial": transform.shift_radial,
        "shift_vector": transform.shift_vector,
        "pivot_shifted": transform.pivot_shifted,
        "shifted_radius": transform.shifted_radius,
        "twist_axis_point_pre_align": transform.twist_axis_point_pre_align,
        "twist_axis_point": transform.twist_axis_point,
        "twist_axis_dir": transform.twist_axis_dir,
        "align_mode": transform.align_mode,
        "align_translation": transform.align_translation,
    }


def bend_structure(
    records,
    residues: "OrderedDict[Tuple[str, int], Residue]",
    input_pdb: str,
    selected_key: object,
    phi_deg: object,
    beta_deg: object,
    tau_deg: object = 0.0,
    shift_axial: object = 0.0,
    shift_radial: object = 0.0,
    sep_mode: str = "n",
    align_mode: str = "y",
    output_pdb: Optional[str] = None,
    axis_range_defs: Optional[List[AxisRangeDefinition]] = None,
) -> Tuple[str, Dict[str, object]]:
    """Bend at one pivot, or at several in order, and link the pieces.

    ``selected_key`` is one resolved pivot key or a sequence of them in bending
    order. Each bend value is one number shared by every pivot, or a sequence
    of one value per pivot. With n pivots the duplex splits into n + 1 pieces:
    piece #1 keeps the input coordinates and piece #k + 1 takes those of the
    helix bend k generated, so the unused rest of each generated helix is
    dropped.
    """
    selected_keys = _selected_key_tuple(selected_key)
    values = parse_parameter_set(
        len(selected_keys),
        phi=phi_deg,
        beta=beta_deg,
        tau=tau_deg,
        shift_axial=shift_axial,
        shift_radial=shift_radial,
    )
    preparations = prepare_bend_pivots(
        residues, selected_keys, axis_range_defs=axis_range_defs
    )
    sequence = build_bend_sequence(
        preparations,
        values["phi"],
        values["beta"],
        values["tau"],
        values["shift_axial"],
        values["shift_radial"],
        align_mode=align_mode,
    )

    first = preparations[0]
    pair_keys = first.pair_keys
    borders = [0] + [item.pair_idx for item in preparations] + [len(pair_keys)]
    # Piece j holds base pairs borders[j]..borders[j + 1] - 1 and comes from
    # helix j: the input for piece 0, the helix bend j generated otherwise.
    piece_key_sets = [
        frozenset(
            key for pair in pair_keys[borders[index]:borders[index + 1]] for key in pair
        )
        for index in range(len(preparations) + 1)
    ]
    helix_of_key = {
        key: helix_index
        for helix_index, keys in enumerate(piece_key_sets)
        for key in keys
    }

    for rec in records:
        if isinstance(rec, AtomRecord):
            helix_index = helix_of_key.get((rec.chain_id, rec.res_seq), 0)
            if helix_index:
                rec.set_coord(sequence.helix_coord(helix_index, rec.coord()))

    piece_chain_maps = None
    if sep_mode == "y":
        piece_chain_maps = separate_piece_chains(
            records,
            piece_key_sets[1:],
            list(first.duplex_chains),
        )

    out_path = normalize_output_path(output_pdb) or make_bend_output_name(
        input_pdb,
        tuple(item.selected_key for item in preparations),
        values["phi"],
        values["beta"],
        values["tau"],
        values["shift_axial"],
        values["shift_radial"],
        sep_mode=sep_mode,
    )
    bends = tuple(
        _bend_step_info(index, preparation, carried, transform)
        for index, (preparation, carried, transform) in enumerate(
            zip(preparations, sequence.preparations, sequence.transforms)
        )
    )
    pieces = tuple(
        {
            "piece": index + 1,
            "helix": index,
            "pair_start": borders[index] + 1,
            "pair_end": borders[index + 1],
            "pivot": None if index == 0 else preparations[index - 1].selected_key,
            "chain_map": (
                piece_chain_maps[index - 1]
                if piece_chain_maps is not None and index > 0
                else None
            ),
        }
        for index in range(len(preparations) + 1)
    )
    # The top-level keys describe bend 1, as they always described the one bend.
    info = dict(bends[0])
    info.update(
        {
            "n_pairs": len(pair_keys),
            "piece2_pair_start": first.pair_idx + 1,
            "piece2_pair_end": len(pair_keys),
            "sep_mode": sep_mode,
            "piece2_chain_map": piece_chain_maps[0] if piece_chain_maps else None,
            "piece_chain_maps": piece_chain_maps,
            "duplex_chains": first.duplex_chains,
            "output_pdb": out_path,
            "pivots": tuple(item.selected_key for item in preparations),
            "bend_values": values,
            "bends": bends,
            "pieces": pieces,
            "bend_sequence": sequence,
        }
    )
    return out_path, info



def rewrite_ter_line(template_line: str, last_atom: Optional[AtomRecord]) -> str:
    if last_atom is None:
        return template_line

    raw = template_line.rstrip("\n")
    if len(raw) < 27:
        raw = raw.ljust(27)

    serial_field = raw[6:11] if len(raw) >= 11 else "     "
    updated = (
        f"{raw[:6]}{serial_field}{raw[11:17]}"
        f"{last_atom.line[17:20]}{raw[20:21]}{last_atom.chain_id}{last_atom.res_seq:4d}"
        f"{raw[26:]}"
    )
    return updated + "\n"



def clean_remark_value(value: object) -> str:
    """Return a compact value for parse-friendly REMARK key=value fields."""
    text = str(value)
    return text.replace("\n", " ").replace("\r", " ").strip()


def build_bend_remark_lines(command: Optional[str] = None) -> List[str]:
    """Build the RE_SCRIPT provenance records written into every output PDB."""
    lines = [
        f"{REMARK_PREFIX} SOFTWARE name={clean_remark_value(SOFTWARE_NAME)} "
        f"version={clean_remark_value(VERSION)} "
        f"developer={clean_remark_value(SOFTWARE_DEVELOPER)}"
    ]
    if command:
        lines.append(f"{REMARK_PREFIX} COMMAND text={clean_remark_value(command)}")
    lines.append(f"{REMARK_PREFIX} OUTPUT_STAGE name={clean_remark_value(SOFTWARE_NAME)}")
    return lines


def record_name_of(record: object) -> str:
    """Return the six-column PDB record name of an atom or passthrough record."""
    if isinstance(record, AtomRecord):
        return record.record_name
    return str(getattr(record, "line", ""))[:6].strip()


def remark_insert_index(records: Sequence[object]) -> int:
    """Return where new REMARK records belong among existing records."""
    last_remark = -1
    for index, record in enumerate(records):
        name = record_name_of(record)
        if name == "REMARK":
            last_remark = index
        elif name in POST_REMARK_RECORDS:
            return last_remark + 1 if last_remark >= 0 else index
    return last_remark + 1 if last_remark >= 0 else len(records)


def insert_remark_records(records: Sequence[object], remark_lines: Sequence[str]):
    """Return a new record list with the REMARK records spliced into the header.

    ``read_pdb`` opens the input in universal-newline mode, so every passthrough
    record already carries a bare LF whatever the input used; new records match.
    """
    result = list(records)
    if not remark_lines:
        return result
    index = remark_insert_index(result)
    result[index:index] = [RawRecord(line=line + "\n") for line in remark_lines]
    return result


def write_pdb(records, out_path: str, update_ter: bool = False) -> None:
    last_atom: Optional[AtomRecord] = None
    with open(out_path, "w") as out:
        for rec in records:
            if isinstance(rec, AtomRecord):
                out.write(rec.to_line())
                last_atom = rec
            else:
                if update_ter and rec.line[:3] == "TER":
                    out.write(rewrite_ter_line(rec.line, last_atom))
                else:
                    out.write(rec.line)



def clone_atom_record(atom: AtomRecord) -> AtomRecord:
    return AtomRecord(
        line=atom.line,
        record_name=atom.record_name,
        atom_name=atom.atom_name,
        chain_id=atom.chain_id,
        res_seq=atom.res_seq,
        x=atom.x,
        y=atom.y,
        z=atom.z,
    )



def clone_records(records):
    cloned = []
    for rec in records:
        if isinstance(rec, AtomRecord):
            cloned.append(clone_atom_record(rec))
        else:
            cloned.append(RawRecord(line=rec.line))
    return cloned



def atom_to_line_with_serial(atom: AtomRecord, serial: int) -> str:
    # An overlay with one full helix per bend can pass serial 99999; wrap it so
    # the five-column field never spills into the next one.
    return (
        f"{atom.line[:6]}{serial % 100000:5d}{atom.line[11:21]}{atom.chain_id}{atom.line[22:30]}"
        f"{atom.x:8.3f}{atom.y:8.3f}{atom.z:8.3f}{atom.line[54:]}"
    )



def ter_line_with_serial(serial: int, last_atom: AtomRecord) -> str:
    return f"TER   {serial % 100000:5d}      {last_atom.line[17:20]} {last_atom.chain_id}{last_atom.res_seq:4d}\n"



def build_origin_overlay_model_maps(
    chain_order: Sequence[str],
    model_count: int = 2,
) -> Tuple[Dict[str, str], ...]:
    """Return one source-to-overlay chain map per ``-ori`` model, in model order.

    Model 1 is the input helix and model k + 1 the full helix bend k generated,
    so a single bend gives A/B and C/D, and each further bend adds two IDs.
    """
    chains = list(chain_order)
    if not chains:
        raise ValueError("No duplex chains are available for origin-overlay mapping.")
    overlay_ids = choose_new_chain_ids(
        [], len(chains) * model_count, purpose="the origin overlay"
    )
    return tuple(
        {
            old: overlay_ids[model_index * len(chains) + chain_index]
            for chain_index, old in enumerate(chains)
        }
        for model_index in range(model_count)
    )


def _normalized_screening_token(value: str) -> str:
    return value.strip().lower().replace("-", "_").replace(" ", "_")


def select_screening_axis_range_specs(
    request: ScreeningRequest,
    main_axis_range_specs: Optional[Iterable[str]],
    popup_local_axis_range_specs: Optional[Iterable[str]],
) -> List[str]:
    """Use popup-owned local ranges only for local-axis rotation screening."""
    main_specs = [str(spec).strip() for spec in main_axis_range_specs or () if str(spec).strip()]
    popup_specs = [
        str(spec).strip()
        for spec in popup_local_axis_range_specs or ()
        if str(spec).strip()
    ]
    mode = _normalized_screening_token(request.mode)
    uses_local_axis = (
        mode in ("rotation", "screening_for_rotation")
        and request.axis is not None
        and _normalized_screening_token(request.axis.source)
        in ("local", "local_axis", "axis_range", "axis_ranges")
    )
    if not uses_local_axis:
        return main_specs
    if not popup_specs:
        raise ValueError(
            "Local-axis rotation screening requires Local axis range(s) in the "
            "Screening to achieve window."
        )
    return popup_specs


def _normalized_atom_name(value: str) -> str:
    return value.strip().upper().replace("*", "'")


def _finite_point3d(value: object, label: str) -> Point3D:
    if isinstance(value, str):
        raise ValueError(f"{label} must contain exactly three numeric values.")
    try:
        values = tuple(float(component) for component in value)  # type: ignore[union-attr]
    except (TypeError, ValueError):
        raise ValueError(f"{label} must contain exactly three numeric values.")
    if len(values) != 3:
        raise ValueError(f"{label} must contain exactly three numeric values.")
    if not all(math.isfinite(component) for component in values):
        raise ValueError(f"{label} values must be finite.")
    return values  # type: ignore[return-value]


def _finite_unit_vector(value: object, label: str) -> Point3D:
    vector = _finite_point3d(value, label)
    if v_len(vector) < EPS:
        raise ValueError(f"{label} cannot be zero.")
    return v_norm(vector)


def parse_overlay_atom_selector(value: object) -> OverlayAtomSelector:
    """Parse an atom selector in the chain namespace of the origin overlay."""
    if isinstance(value, OverlayAtomSelector):
        chain_id = value.chain_id
        res_seq = value.res_seq
        atom_name = value.atom_name
    elif isinstance(value, (tuple, list)) and len(value) == 3:
        chain_id, res_seq, atom_name = value
    elif isinstance(value, str):
        text = value.strip()
        separated = text.replace("/", ":").split(":")
        if len(separated) == 3:
            chain_id, residue_text, atom_name = (
                part.strip() for part in separated
            )
            try:
                res_seq = int(residue_text)
            except ValueError:
                raise ValueError(
                    f"Invalid overlay atom selector '{value}'. Use A:30:P, A30:P, or 30A:P."
                )
        elif len(separated) == 2:
            residue_selector, atom_name = (
                part.strip() for part in separated
            )
            match = re.fullmatch(
                r"(?:([A-Za-z0-9])(-?\d+)|(-?\d+)([A-Za-z0-9]))",
                residue_selector,
            )
            if match is None:
                raise ValueError(
                    f"Invalid overlay atom selector '{value}'. Use A:30:P, A30:P, or 30A:P."
                )
            if match.group(1) is not None:
                chain_id = match.group(1)
                res_seq = int(match.group(2))
            else:
                chain_id = match.group(4)
                res_seq = int(match.group(3))
        else:
            raise ValueError(
                f"Invalid overlay atom selector '{value}'. Use A:30:P, A30:P, or 30A:P."
            )
    else:
        raise ValueError(
            "Overlay atom selector must be A:30:P, a compact equivalent, or "
            "(chain, residue, atom)."
        )

    chain_text = str(chain_id).strip()
    atom_text = str(atom_name).strip()
    try:
        residue_number = int(res_seq)
    except (TypeError, ValueError):
        raise ValueError("Overlay atom residue number must be an integer.")
    if len(chain_text) != 1 or not atom_text:
        raise ValueError(
            "Overlay atom selector requires one chain-ID character and a nonblank atom name."
        )
    return OverlayAtomSelector(chain_text, residue_number, atom_text)


def parse_overlay_atom_selectors(value: object) -> Tuple[OverlayAtomSelector, ...]:
    """Parse one selector or comma/semicolon-separated selectors for a centroid."""
    if not isinstance(value, str):
        return (parse_overlay_atom_selector(value),)
    parts = re.split(r"[,;]", value)
    if any(not part.strip() for part in parts):
        raise ValueError(
            "Provide one or more overlay atoms as CHAIN:RESIDUE:ATOM, separated by "
            "commas or semicolons, without empty entries."
        )
    return tuple(parse_overlay_atom_selector(part) for part in parts)


def _overlay_source_atom_on_helix(
    context: ScreeningContext,
    selector: object,
) -> Tuple[ScreeningAtom, int]:
    """Return the source atom and the overlay helix (0 = input) a selector names."""
    parsed = parse_overlay_atom_selector(selector)
    chain_mapping = context.overlay_model_map
    if parsed.chain_id not in chain_mapping:
        available = ", ".join(sorted(chain_mapping))
        raise ValueError(
            f"Overlay chain '{parsed.chain_id}' is not available; choose one of {available}."
        )
    source_chain, helix_index = chain_mapping[parsed.chain_id]
    wanted_name = _normalized_atom_name(parsed.atom_name)
    matches = [
        atom
        for atom in context.atoms
        if atom.source_chain_id == source_chain
        and atom.res_seq == parsed.res_seq
        and _normalized_atom_name(atom.atom_name) == wanted_name
    ]
    label = f"{parsed.chain_id}:{parsed.res_seq}:{parsed.atom_name}"
    if not matches:
        raise ValueError(f"Overlay atom selector '{label}' did not match any atom.")
    if len(matches) > 1:
        raise ValueError(
            f"Overlay atom selector '{label}' matched multiple atoms; choose an unambiguous atom."
        )
    return matches[0], helix_index


def resolve_overlay_atom_coordinate(
    context: ScreeningContext,
    selector: object,
    transform: BendCandidate,
) -> Point3D:
    """Resolve an origin-overlay atom: A/B input, C/D bend 1's helix, and so on."""
    atom, helix_index = _overlay_source_atom_on_helix(context, selector)
    return transform.helix_coord(helix_index, atom.coord)


def _compile_screening_point(
    context: ScreeningContext,
    reference: ScreeningPoint,
) -> Callable[[BendCandidate], Point3D]:
    if not isinstance(reference, ScreeningPoint):
        raise ValueError("Screening point must be a ScreeningPoint value.")
    kind = _normalized_screening_token(reference.kind)
    if kind in ("overlay_atom", "atom"):
        atoms = tuple(
            _overlay_source_atom_on_helix(context, selector)
            for selector in parse_overlay_atom_selectors(reference.value)
        )
        if len(atoms) == 1:
            atom, helix_index = atoms[0]
            if helix_index:
                return lambda sequence: sequence.helix_coord(helix_index, atom.coord)
            return lambda _sequence: atom.coord

        def resolve_centroid(sequence: BendCandidate) -> Point3D:
            return centroid([
                sequence.helix_coord(helix_index, atom.coord)
                for atom, helix_index in atoms
            ])

        return resolve_centroid
    if kind in ("xyz", "xyz_point", "point"):
        point = _finite_point3d(reference.value, "XYZ screening point")
        return lambda _sequence: point
    if kind in (
        "phi_corrected_pivot",
        "phi_corrected_pivot_p",
        "pivot",
    ):
        # The first pivot's, whose bend acts on the input helix.
        return lambda sequence: sequence.transforms[0].hinge_point
    raise ValueError(
        f"Unknown screening point kind '{reference.kind}'; expected overlay_atom, "
        "xyz, or phi_corrected_pivot."
    )


def resolve_screening_point(
    context: ScreeningContext,
    reference: ScreeningPoint,
    transform: BendCandidate,
) -> Point3D:
    """Resolve a point reference for one bend candidate."""
    return _compile_screening_point(context, reference)(transform)


def _axis_pair_references(
    axis: ScreeningAxis,
    expected_kind: str,
) -> Tuple[ScreeningPoint, ScreeningPoint]:
    if axis.point1 is not None and axis.point2 is not None:
        return axis.point1, axis.point2
    raw = axis.vector
    if isinstance(raw, (tuple, list)) and len(raw) == 2:
        first, second = raw
        if expected_kind == "xyz":
            return ScreeningPoint("xyz", first), ScreeningPoint("xyz", second)
        return ScreeningPoint("overlay_atom", first), ScreeningPoint(
            "overlay_atom", second
        )
    if isinstance(raw, (tuple, list)) and len(raw) == 6 and expected_kind == "xyz":
        return ScreeningPoint("xyz", raw[:3]), ScreeningPoint("xyz", raw[3:])
    raise ValueError(
        "Two-point axis vector source requires point1 and point2 (or a matching pair in vector)."
    )


def _compile_screening_axis(
    context: ScreeningContext,
    axis: ScreeningAxis,
) -> Callable[[BendCandidate], Tuple[Point3D, Point3D]]:
    if not isinstance(axis, ScreeningAxis):
        raise ValueError("Rotation screening requires a ScreeningAxis value.")
    source = _normalized_screening_token(axis.source)
    if source in ("local", "local_axis", "axis_range", "axis_ranges"):
        # The first pivot's local axis on the input helix.
        point = context.preparation.axis_point
        direction = context.preparation.axis_dir
        return lambda _sequence: (point, direction)
    if source not in ("geometric", "geometry"):
        raise ValueError(
            f"Unknown screening axis source '{axis.source}'; expected local_axis or geometric."
        )
    if axis.point is None:
        raise ValueError("A geometric screening axis requires an axis point.")
    point_resolver = _compile_screening_point(context, axis.point)
    vector_source = _normalized_screening_token(axis.vector_source)

    if vector_source in ("direct", "direct_vector", "vector"):
        direction = _finite_unit_vector(axis.vector, "Axis direction vector")
        return lambda sequence: (point_resolver(sequence), direction)

    if vector_source in ("two_xyz", "two_xyz_points", "xyz_points"):
        first_ref, second_ref = _axis_pair_references(axis, "xyz")
        first_resolver = _compile_screening_point(context, first_ref)
        second_resolver = _compile_screening_point(context, second_ref)
    elif vector_source in ("two_atoms", "two_overlay_atoms", "overlay_atoms"):
        first_ref, second_ref = _axis_pair_references(axis, "overlay_atom")
        first_resolver = _compile_screening_point(context, first_ref)
        second_resolver = _compile_screening_point(context, second_ref)
    elif vector_source in ("normal", "normal_vectors", "normal_to_two_vectors"):
        raw_first = axis.normal_vector1
        raw_second = axis.normal_vector2
        if raw_first is None or raw_second is None:
            raw = axis.vector
            if isinstance(raw, (tuple, list)) and len(raw) == 2:
                raw_first, raw_second = raw
            elif isinstance(raw, (tuple, list)) and len(raw) == 6:
                raw_first, raw_second = raw[:3], raw[3:]
            else:
                raise ValueError("Normal-vector axis source requires two XYZ vectors.")
        first = _finite_point3d(raw_first, "Normal-defining vector 1")
        second = _finite_point3d(raw_second, "Normal-defining vector 2")
        normal = v_cross(first, second)
        if v_len(normal) < EPS:
            raise ValueError("Normal-defining vectors cannot be zero or parallel.")
        direction = v_norm(normal)
        return lambda sequence: (point_resolver(sequence), direction)
    else:
        raise ValueError(
            f"Unknown geometric axis vector source '{axis.vector_source}'."
        )

    def resolve_from_points(sequence: BendCandidate) -> Tuple[Point3D, Point3D]:
        first = first_resolver(sequence)
        second = second_resolver(sequence)
        direction = v_sub(second, first)
        if v_len(direction) < EPS:
            raise ValueError("Axis vector-defining points cannot coincide.")
        return point_resolver(sequence), v_norm(direction)

    return resolve_from_points


def resolve_screening_axis(
    context: ScreeningContext,
    axis: ScreeningAxis,
    transform: BendCandidate,
) -> Tuple[Point3D, Point3D]:
    """Resolve ``(axis_point, unit_axis_direction)`` for one candidate."""
    return _compile_screening_axis(context, axis)(transform)


def distance_between_points(point1: Point3D, point2: Point3D) -> float:
    """Return the Euclidean distance between two finite XYZ points."""
    first = _finite_point3d(point1, "Distance point 1")
    second = _finite_point3d(point2, "Distance point 2")
    return v_len(v_sub(second, first))


def signed_projected_angle_deg(
    point1: Point3D,
    point2: Point3D,
    axis_point: Point3D,
    axis_dir: Point3D,
) -> float:
    """Return the signed point-1-to-point-2 rotation around an axis."""
    first = _finite_point3d(point1, "Rotation point 1")
    second = _finite_point3d(point2, "Rotation point 2")
    origin = _finite_point3d(axis_point, "Rotation axis point")
    direction = _finite_unit_vector(axis_dir, "Rotation axis direction")
    first_rel = v_sub(first, origin)
    second_rel = v_sub(second, origin)
    first_projected = v_sub(
        first_rel, v_scale(direction, v_dot(first_rel, direction))
    )
    second_projected = v_sub(
        second_rel, v_scale(direction, v_dot(second_rel, direction))
    )
    if v_len(first_projected) < EPS or v_len(second_projected) < EPS:
        raise ValueError(
            "Rotation screening points must not lie on the rotation axis."
        )
    first_unit = v_norm(first_projected)
    second_unit = v_norm(second_projected)
    sine = v_dot(direction, v_cross(first_unit, second_unit))
    cosine = max(-1.0, min(1.0, v_dot(first_unit, second_unit)))
    return math.degrees(math.atan2(sine, cosine))


def wrapped_angle_error_deg(actual: float, target: float) -> float:
    """Return the absolute shortest circular difference in degrees."""
    actual_value = float(actual)
    target_value = float(target)
    if not math.isfinite(actual_value) or not math.isfinite(target_value):
        raise ValueError("Rotation angles must be finite.")
    difference = (actual_value - target_value + 180.0) % 360.0 - 180.0
    return abs(difference)


_SCREEN_VARIABLE_ALIASES: Mapping[str, str] = {
    "phi": "phi",
    "beta": "beta",
    "tau": "tau",
    "shift_axial": "shift_axial",
    "axial_shift": "shift_axial",
    "axial": "shift_axial",
    "sa": "shift_axial",
    "shift_radial": "shift_radial",
    "radial_shift": "shift_radial",
    "radial": "shift_radial",
    "sr": "shift_radial",
}


def _normalize_screen_variable_name(name: str) -> str:
    """Resolve one screened-variable name or alias to its canonical spelling."""
    normalized = _normalized_screening_token(name)
    for unit_suffix in ("_deg", "_a", "_ang"):
        if normalized.endswith(unit_suffix) and normalized != unit_suffix:
            normalized = normalized[: -len(unit_suffix)]
            break
    resolved = _SCREEN_VARIABLE_ALIASES.get(normalized)
    if resolved is None:
        raise ValueError(
            f"Unknown screened variable '{name}'; expected one of "
            + ", ".join(SCREEN_VARIABLE_NAMES)
            + "."
        )
    return resolved


def _angle_range_value_count(angle_range: ScreenAngleRange) -> int:
    start = float(angle_range.start)
    stop = float(angle_range.stop)
    step = float(angle_range.step)
    if not all(math.isfinite(value) for value in (start, stop, step)):
        raise ValueError("Screen angle range values must be finite.")
    if step <= 0.0:
        raise ValueError("Screen angle range step must be positive.")
    span = abs(stop - start)
    if not math.isfinite(span):
        raise ValueError("Screen angle range span is too large.")
    if span == 0.0:
        return 1
    quotient = span / step
    if not math.isfinite(quotient):
        raise ValueError("Screen angle range contains too many values.")
    if quotient < 1.0:
        return 2
    nearest_integer = round(quotient)
    if math.isclose(quotient, nearest_integer, rel_tol=1.0e-12, abs_tol=1.0e-12):
        return int(nearest_integer) + 1
    return int(math.floor(quotient)) + 2


def inclusive_angle_values(angle_range: ScreenAngleRange) -> Tuple[float, ...]:
    """Expand an inclusive ascending or descending positive-step angle grid."""
    count = _angle_range_value_count(angle_range)
    start = float(angle_range.start)
    stop = float(angle_range.stop)
    step = float(angle_range.step)
    if count == 1:
        return (start,)
    direction = 1.0 if stop > start else -1.0
    values = [start + direction * step * index for index in range(count - 1)]
    return tuple(values) + (stop,)


def validate_screen_angle_ranges(
    ranges: Sequence[ScreenAngleRange],
    candidate_cap: int,
) -> Tuple[
    Tuple[ScreenAngleRange, ...],
    Tuple[Tuple[float, ...], ...],
    int,
]:
    """Validate one/two unique grids and enforce the total candidate cap."""
    supplied = tuple(ranges)
    if len(supplied) not in (1, 2):
        raise ValueError(
            "Screening requires exactly one or two screened variables."
        )
    if isinstance(candidate_cap, bool) or int(candidate_cap) != candidate_cap:
        raise ValueError("Screening candidate cap must be a positive integer.")
    cap = int(candidate_cap)
    if cap <= 0:
        raise ValueError("Screening candidate cap must be a positive integer.")

    normalized: List[ScreenAngleRange] = []
    names = set()
    counts: List[int] = []
    for angle_range in supplied:
        if not isinstance(angle_range, ScreenAngleRange):
            raise ValueError("Each screening grid must be a ScreenAngleRange.")
        name = _normalize_screen_variable_name(angle_range.name)
        if name in names:
            raise ValueError(f"Screened variable '{name}' was supplied more than once.")
        names.add(name)
        normalized_range = ScreenAngleRange(
            name,
            float(angle_range.start),
            float(angle_range.stop),
            float(angle_range.step),
        )
        normalized.append(normalized_range)
        counts.append(_angle_range_value_count(normalized_range))

    candidate_count = math.prod(counts)
    if candidate_count > cap:
        raise ValueError(
            f"Screening grid contains {candidate_count} candidates, exceeding the "
            f"candidate cap of {cap}."
        )
    values = tuple(inclusive_angle_values(item) for item in normalized)
    return tuple(normalized), values, candidate_count


def format_screening_grid_preview(
    ranges: Sequence[ScreenAngleRange],
    max_values_per_angle: int = 24,
) -> str:
    """Format calculated coarse-grid values and their Cartesian-product count."""
    normalized, grid_values, candidate_count = validate_screen_angle_ranges(
        ranges, candidate_cap=250000
    )
    lines = []
    for angle_range, values in zip(normalized, grid_values):
        formatted = [format_float_for_cli(value) for value in values]
        if len(formatted) > max_values_per_angle:
            displayed = formatted[:12] + ["..."] + formatted[-6:]
        else:
            displayed = formatted
        label = SCREEN_VARIABLE_LABELS.get(
            angle_range.name, angle_range.name.capitalize()
        )
        lines.append(
            f"{label} grid ({len(values)}): "
            + ", ".join(displayed)
            + " "
            + screen_variable_unit(angle_range.name)
        )
    lines.append(f"Total coarse candidates: {candidate_count}")
    return "\n".join(lines)


def format_screening_solution_table(
    result: ScreeningResult,
    unit: str,
    include_shifts: Optional[bool] = None,
) -> str:
    """Format all reported screening solutions in deterministic result order."""
    status = (
        f"{result.solution_count} distinct solution(s) within tolerance"
        if result.target_tolerance_met
        else "no solution met tolerance; closest fallback shown"
    )
    if include_shifts is None:
        # Pure-angle runs keep the historical three-column layout.
        include_shifts = any(
            solution.shift_axial != 0.0 or solution.shift_radial != 0.0
            for solution in result.solutions
        )
    shift_header = (
        "shift axial (A)  shift radial (A)  " if include_shifts else ""
    )
    lines = [
        (
            f"Reported solutions ({status}; tolerance "
            f"{result.solution_tolerance:.9g} {unit}):"
        ),
        (
            "  #  phi (deg)       beta (deg)      tau (deg)       "
            f"{shift_header}achieved ({unit})     residual ({unit})"
        ),
    ]
    for index, solution in enumerate(result.solutions, start=1):
        shift_columns = (
            f"{format_float_for_cli(solution.shift_axial):<17}"
            f"{format_float_for_cli(solution.shift_radial):<18}"
            if include_shifts
            else ""
        )
        lines.append(
            f"  {index:<3d}"
            f"{format_float_for_cli(solution.phi_deg):<16}"
            f"{format_float_for_cli(solution.beta_deg):<16}"
            f"{format_float_for_cli(solution.tau_deg):<16}"
            f"{shift_columns}"
            f"{solution.achieved_value:<17.9g}"
            f"{solution.error:.9g}"
        )
    return "\n".join(lines)


def prepare_screening_context_from_records(
    input_pdb: str,
    records: Iterable[object],
    residues: "OrderedDict[Tuple[str, int], Residue]",
    selected_key: object,
    axis_range_defs: Optional[List[AxisRangeDefinition]] = None,
) -> ScreeningContext:
    """Snapshot already-parsed records into an immutable screening context.

    ``selected_key`` is one resolved pivot key or a sequence of them in bending
    order; the screened values then apply at every pivot.
    """
    preparations = prepare_bend_pivots(
        residues, selected_key, axis_range_defs=axis_range_defs
    )
    preparation = preparations[0]
    model_maps = build_origin_overlay_model_maps(
        preparation.duplex_chains, len(preparations) + 1
    )
    atoms = tuple(
        ScreeningAtom(
            source_chain_id=record.chain_id,
            res_seq=record.res_seq,
            atom_name=record.atom_name,
            coord=record.coord(),
        )
        for record in records
        if isinstance(record, AtomRecord)
        and record.chain_id in preparation.duplex_chains
    )
    return ScreeningContext(
        input_pdb=input_pdb,
        preparation=preparation,
        atoms=atoms,
        model1_chain_map_items=tuple(model_maps[0].items()),
        model2_chain_map_items=tuple(model_maps[1].items()),
        preparations=preparations if len(preparations) > 1 else (),
        extra_model_chain_map_items=tuple(
            tuple(chain_map.items()) for chain_map in model_maps[2:]
        ),
    )


def prepare_screening_context(
    input_pdb: str,
    pivot_residue: str,
    axis_range_specs: Optional[Iterable[str]] = None,
) -> ScreeningContext:
    """Read a PDB and prepare a non-mutating context for repeated candidates.

    ``pivot_residue`` names one pivot or several, in bending order.
    """
    records, residues = read_pdb(input_pdb)
    raw_axis_defs = parse_axis_range_specs(axis_range_specs)
    available_chains: List[str] = []
    seen_chains = set()
    for residue in residues.values():
        if residue.p_atom is not None and residue.chain_id not in seen_chains:
            available_chains.append(residue.chain_id)
            seen_chains.add(residue.chain_id)
    axis_range_defs = resolve_axis_range_definitions(
        raw_axis_defs, available_chains
    )
    selected_keys = tuple(
        resolve_selected_key(parse_residue_token(token), residues)
        for token in parse_pivot_tokens(pivot_residue)
    )
    return prepare_screening_context_from_records(
        input_pdb=input_pdb,
        records=records,
        residues=residues,
        selected_key=selected_keys,
        axis_range_defs=axis_range_defs,
    )


def screen_bend_angles(
    context: ScreeningContext,
    fixed_angles: Mapping[str, float],
    ranges: Sequence[ScreenAngleRange],
    request: ScreeningRequest,
    align_mode: str = "y",
    candidate_cap: int = 250000,
    solution_tolerance: float = DEFAULT_SCREEN_SOLUTION_TOLERANCE,
) -> ScreeningResult:
    """Refine every promising coarse region and report distinct target matches.

    ``fixed_angles`` must supply every unscreened angle; an unscreened pivot
    shift defaults to 0. With several pivots in ``context``, every fixed and
    screened value applies at each pivot, and the bends chain in pivot order.
    """
    if not isinstance(context, ScreeningContext):
        raise ValueError("Screening requires a ScreeningContext.")
    if not isinstance(request, ScreeningRequest):
        raise ValueError("Screening requires a ScreeningRequest.")
    normalized_ranges, grid_values, candidate_count = (
        validate_screen_angle_ranges(ranges, candidate_cap)
    )
    align_mode = normalize_align(align_mode)
    target = float(request.target)
    if not math.isfinite(target):
        raise ValueError("Screening target must be finite.")
    solution_tolerance = float(solution_tolerance)
    if not math.isfinite(solution_tolerance) or solution_tolerance < 0.0:
        raise ValueError("Screening solution tolerance must be finite and nonnegative.")

    screened_names = {angle_range.name for angle_range in normalized_ranges}
    normalized_fixed: Dict[str, float] = {}
    for raw_name, raw_value in fixed_angles.items():
        name = _normalize_screen_variable_name(raw_name)
        value = float(raw_value)
        if not math.isfinite(value):
            raise ValueError(f"Fixed value for '{name}' must be finite.")
        normalized_fixed[name] = value
    for name in SCREEN_ANGLE_NAMES:
        if name not in screened_names and name not in normalized_fixed:
            raise ValueError(f"Fixed value for unscreened angle '{name}' is required.")
    for name in SCREEN_SHIFT_NAMES:
        # An unscreened pivot shift defaults to no shift, so pre-V2.7 callers
        # that only supply angles keep working unchanged.
        if name not in screened_names:
            normalized_fixed.setdefault(name, 0.0)

    point1_resolver = _compile_screening_point(context, request.point1)
    point2_resolver = _compile_screening_point(context, request.point2)
    mode = _normalized_screening_token(request.mode)
    if mode in ("distance", "screening_for_distance"):
        if target < 0.0:
            raise ValueError("Distance screening target cannot be negative.")
        axis_resolver = None
    elif mode in ("rotation", "screening_for_rotation"):
        if request.axis is None:
            raise ValueError("Rotation screening requires an axis definition.")
        axis_resolver = _compile_screening_axis(context, request.axis)
    else:
        raise ValueError(
            f"Unknown screening mode '{request.mode}'; expected distance or rotation."
        )

    best_evaluation = None
    first_candidate_error: Optional[Exception] = None

    evaluation_cache = {}

    def evaluate_candidate(angles: Mapping[str, float]):
        nonlocal best_evaluation, first_candidate_error
        candidate_key = tuple(angles[name] for name in SCREEN_VARIABLE_NAMES)
        if candidate_key in evaluation_cache:
            return evaluation_cache[candidate_key]
        try:
            sequence = build_bend_sequence(
                context.pivot_preparations,
                (angles["phi"],),
                (angles["beta"],),
                (angles["tau"],),
                (angles["shift_axial"],),
                (angles["shift_radial"],),
                align_mode=align_mode,
            )
            point1 = point1_resolver(sequence)
            point2 = point2_resolver(sequence)
            if axis_resolver is None:
                achieved = distance_between_points(point1, point2)
                error = abs(achieved - target)
            else:
                axis_point, axis_dir = axis_resolver(sequence)
                achieved = signed_projected_angle_deg(
                    point1, point2, axis_point, axis_dir
                )
                error = wrapped_angle_error_deg(achieved, target)
        except (ValueError, OverflowError) as exc:
            if first_candidate_error is None:
                first_candidate_error = exc
            evaluation_cache[candidate_key] = None
            return None

        candidate_angles = dict(angles)
        key = (error,) + candidate_key
        evaluation = (key, candidate_angles, achieved)
        evaluation_cache[candidate_key] = evaluation
        if best_evaluation is None or key < best_evaluation[0]:
            best_evaluation = evaluation
        return evaluation

    coarse_evaluations = {}
    grid_index_ranges = tuple(range(len(values)) for values in grid_values)
    for candidate_indices in itertools.product(*grid_index_ranges):
        candidate_values = tuple(
            grid_values[index][candidate_index]
            for index, candidate_index in enumerate(candidate_indices)
        )
        angles = dict(normalized_fixed)
        for angle_range, value in zip(normalized_ranges, candidate_values):
            angles[angle_range.name] = value
        evaluation = evaluate_candidate(angles)
        coarse_evaluations[candidate_indices] = evaluation

    if best_evaluation is None:
        detail = (
            f" First candidate error: {first_candidate_error}"
            if first_candidate_error is not None
            else ""
        )
        raise ValueError(
            "Screening grid did not contain any geometrically valid candidates."
            + detail
        )

    refinement_bounds = {
        angle_range.name: (
            min(angle_range.start, angle_range.stop),
            max(angle_range.start, angle_range.stop),
        )
        for angle_range in normalized_ranges
    }
    initial_refinement_steps = {
        angle_range.name: min(
            angle_range.step / 2.0,
            abs(angle_range.stop - angle_range.start) / 2.0,
        )
        for angle_range in normalized_ranges
    }
    screened_order = tuple(angle_range.name for angle_range in normalized_ranges)
    neighbor_offsets = tuple(
        offsets
        for offsets in itertools.product((-1, 0, 1), repeat=len(screened_order))
        if any(offset != 0 for offset in offsets)
    )
    promising_coarse_candidates = []
    for candidate_indices, evaluation in coarse_evaluations.items():
        if evaluation is None:
            continue
        has_better_neighbor = False
        for offsets in neighbor_offsets:
            neighbor_indices = tuple(
                index + offset
                for index, offset in zip(candidate_indices, offsets)
            )
            if any(
                index < 0 or index >= len(grid_values[dimension])
                for dimension, index in enumerate(neighbor_indices)
            ):
                continue
            neighbor = coarse_evaluations.get(neighbor_indices)
            if neighbor is not None and neighbor[0] < evaluation[0]:
                has_better_neighbor = True
                break
        if not has_better_neighbor:
            promising_coarse_candidates.append(evaluation)
    promising_coarse_candidates.sort(key=lambda item: item[0])

    refinement_endpoints = []
    for seed_evaluation in promising_coarse_candidates:
        current_evaluation = seed_evaluation
        refinement_steps = dict(initial_refinement_steps)
        for _round_index in range(SCREEN_REFINEMENT_MAX_ROUNDS):
            if not any(
                refinement_steps[name] > screen_variable_tolerance(name)
                for name in screened_order
            ):
                break

            local_best = current_evaluation
            for offsets in itertools.product((-1.0, 0.0, 1.0), repeat=len(screened_order)):
                if all(offset == 0.0 for offset in offsets):
                    continue
                trial_angles = dict(current_evaluation[1])
                changed = False
                for name, offset in zip(screened_order, offsets):
                    low, high = refinement_bounds[name]
                    trial_value = max(
                        low,
                        min(
                            high,
                            current_evaluation[1][name]
                            + offset * refinement_steps[name],
                        ),
                    )
                    if trial_value != current_evaluation[1][name]:
                        changed = True
                    trial_angles[name] = trial_value
                if not changed:
                    continue
                trial_evaluation = evaluate_candidate(trial_angles)
                if (
                    trial_evaluation is not None
                    and trial_evaluation[0] < local_best[0]
                ):
                    local_best = trial_evaluation

            if local_best[0] < current_evaluation[0]:
                current_evaluation = local_best
            else:
                refinement_steps = {
                    name: step / 2.0 for name, step in refinement_steps.items()
                }

        refinement_endpoints.append(current_evaluation)

    best_key, best_angles, best_achieved = best_evaluation
    refinement_candidate_count = max(0, len(evaluation_cache) - candidate_count)
    reportable_evaluations = [
        evaluation
        for evaluation in coarse_evaluations.values()
        if evaluation is not None and evaluation[0][0] <= solution_tolerance
    ]
    reportable_evaluations.extend(
        evaluation
        for evaluation in refinement_endpoints
        if evaluation[0][0] <= solution_tolerance
    )
    target_tolerance_met = bool(reportable_evaluations)
    if not target_tolerance_met:
        reportable_evaluations = [best_evaluation]

    distinct_solutions = []
    solution_buckets = {}
    # Two candidates are the same solution when every screened variable agrees
    # inside its own refinement precision: 0.001 deg for an angle, 0.001 A for a
    # pivot shift. Only the screened variables can differ between candidates, so
    # bucketing on those keeps the neighbour sweep small.
    dedup_names = tuple(screened_order)
    for evaluation in sorted(reportable_evaluations, key=lambda item: item[0]):
        key, angles, achieved = evaluation
        cell = tuple(
            math.floor(angles[name] / screen_variable_tolerance(name))
            for name in dedup_names
        )
        duplicate = False
        for offsets in itertools.product((-1, 0, 1), repeat=len(dedup_names)):
            neighbor_cell = tuple(
                index + offset for index, offset in zip(cell, offsets)
            )
            for existing in solution_buckets.get(neighbor_cell, ()):
                if all(
                    abs(angles[name] - existing.variables[name])
                    <= screen_variable_tolerance(name)
                    for name in dedup_names
                ):
                    duplicate = True
                    break
            if duplicate:
                break
        if duplicate:
            continue
        solution = ScreeningSolution(
            phi_deg=angles["phi"],
            beta_deg=angles["beta"],
            tau_deg=angles["tau"],
            achieved_value=achieved,
            error=key[0],
            shift_axial=angles["shift_axial"],
            shift_radial=angles["shift_radial"],
        )
        distinct_solutions.append(solution)
        solution_buckets.setdefault(cell, []).append(solution)

    return ScreeningResult(
        phi_deg=best_angles["phi"],
        beta_deg=best_angles["beta"],
        tau_deg=best_angles["tau"],
        shift_axial=best_angles["shift_axial"],
        shift_radial=best_angles["shift_radial"],
        achieved_value=best_achieved,
        error=best_key[0],
        candidate_count=candidate_count,
        refinement_candidate_count=refinement_candidate_count,
        solutions=tuple(distinct_solutions),
        solution_tolerance=solution_tolerance,
        target_tolerance_met=target_tolerance_met,
        refinement_region_count=len(promising_coarse_candidates),
    )



def write_origin_overlay_pdb(
    records,
    out_path: str,
    transform_coord,
    chain_order: List[str],
    remark_lines: Optional[Sequence[str]] = None,
) -> Dict[str, object]:
    """Write the input helix plus every generated full helix, one model each.

    ``transform_coord`` is the one bend's full-helix transform, or a sequence
    of them, one per generated helix in bend order.
    """
    if not chain_order:
        raise ValueError("No duplex chains are available for --origin output.")
    helix_transforms = (
        [transform_coord] if callable(transform_coord) else list(transform_coord)
    )

    chain_to_atoms: "OrderedDict[str, List[AtomRecord]]" = OrderedDict((cid, []) for cid in chain_order)
    for rec in records:
        if isinstance(rec, AtomRecord) and rec.chain_id in chain_to_atoms:
            chain_to_atoms[rec.chain_id].append(rec)

    missing = [cid for cid, atoms in chain_to_atoms.items() if not atoms]
    if missing:
        raise ValueError(
            "Unable to build --origin output because no atoms were found for chain(s): "
            + ", ".join(missing)
        )

    model_maps = build_origin_overlay_model_maps(
        chain_order, len(helix_transforms) + 1
    )

    serial = 1
    with open(out_path, "w") as out:
        for line in remark_lines or ():
            out.write(line + "\n")
        for model_index, chain_map in enumerate(model_maps):
            helix_transform = (
                helix_transforms[model_index - 1] if model_index > 0 else None
            )
            for orig_chain in chain_order:
                last_atom: Optional[AtomRecord] = None
                for atom in chain_to_atoms[orig_chain]:
                    new_atom = clone_atom_record(atom)
                    new_atom.set_chain_id(chain_map[orig_chain])
                    if helix_transform is not None:
                        new_atom.set_coord(helix_transform(atom.coord()))
                    out.write(atom_to_line_with_serial(new_atom, serial))
                    serial += 1
                    last_atom = new_atom
                if last_atom is not None:
                    out.write(ter_line_with_serial(serial, last_atom))
                    serial += 1
        out.write("END\n")

    return {
        "origin_chain_map_model1": model_maps[0],
        "origin_chain_map_model2": model_maps[1],
        "origin_chain_maps": model_maps,
    }


