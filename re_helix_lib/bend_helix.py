#!/usr/bin/env python3
"""
bend_helixV2_6.py

Bend a two-chain nucleic-acid helix at a user-selected phosphorus site.

Usage modes
-----------
1) Positional CLI arguments (backward-compatible):
       bend_helixV2_6.py input.pdb A36 0 30
       # tau defaults to 0 degrees in positional mode.
       # align defaults to y unless you set --align n.

2) Named CLI arguments:
       bend_helixV2_6.py --input A60-heli.pdb --pivot A36 --phi 0 --beta 30 --tau 10 --align y --origin y
       bend_helixV2_6.py --input A60-heli.pdb --pivot A36 --phi 0 --beta 30 --shift_axial 2 --shift_radial -1.5
       bend_helixV2_6.py --input A60-heli.pdb --pivot A36 --phi 0 --beta 30 --axis_range A1-A35,B60-B26 -o bent.pdb
       bend_helixV2_6.py --input A60-heli.pdb --pivot A20,A40 --phi 0,90 --beta 30 --tau -10,5

3) GUI mode:
       bend_helixV2_6.py
       bend_helixV2_6.py --gui

Geometry implemented here
-------------------------
- The input duplex is treated as two paired strands.
- By default, the helix axis is estimated from paired P-atom midpoints.
- With --axis_range, a local helical axis can instead be estimated from user-defined
  residue windows, which is useful for already-bent helices. Use one range per
  line in the GUI or repeat --axis_range on the CLI, e.g. A1-A35,B60-B26.
- The chosen residue defines the *border* base pair between the two rigid pieces.
  Piece 2 contains the chosen base pair and every base pair after it along the
  duplex axis; piece 1 contains the remaining base pairs.
- shift_axial (Sa) and shift_radial (Sr) first translate movable piece 2, in
  angstroms, before any rotation is built. Positive Sa moves piece 2 forward
  along the positive helix axis and negative Sa moves it backward. Positive Sr
  moves piece 2 outward along the pivot P atom's own radial direction, away
  from the helix axis, and negative Sr moves it inward. Both default to 0.
- Every rotation below is then built from the *shifted* pivot position.
- At the axial height of the shifted P atom, we project that atom to the helix
  axis, creating a circle in the plane perpendicular to the axis. Sa slides that
  circle along the axis and Sr changes its radius.
- phi rotates the shifted P position around the axis on that circle.
- The hinge is the tangent line to that circle at the rotated point.
- beta rotates movable piece 2 rigidly about that hinge. Positive beta bends
  piece 2 away from the helix axis in the radial direction defined by phi.
- tau adds an extra twist of movable piece 2 about its own bent helical axis
  relative to fixed piece 1. Positive tau follows the right-hand rule about the bent axis;
  negative tau is left-handed. The twist axis is piece 2's own axis, so it is
  carried along by Sa and Sr.
- With --align y (default), piece 2 is translated after the bend/twist so that
  the pivot residue's P atom returns to its shifted pivot position, which is its
  original pre-bend position when Sa and Sr are both 0.
- With --align n, the result matches the V2.1 bend/twist behaviour.
- With --sep y, piece 2 is additionally written under new chain IDs so that
  piece 1 and piece 2 are separated in the final PDB.
- Output filenames are written as *_PvCccRrr_PxByTz.pdb, or
  *_PvCccRrr_PxByTz_sep.pdb when --sep y is used, unless -o/--output is
  provided. The leading Pv block names the pivot residue, for example PvA36.
  When either shift is nonzero, SaaSrr is appended to the angle block, giving
  *_PvA36_PxByTzSaaSrr.pdb.
- Every output PDB records how it was made as REMARK 950 RE_SCRIPT SOFTWARE,
  COMMAND and OUTPUT_STAGE lines, using the same convention as the other
  bundled tools. The COMMAND record holds the equivalent CLI command, so the
  model can be regenerated from the file itself.
- With --origin y, an additional <main-output>-ori.pdb file is written that
  contains the original full helix and the same rigid full-helix transform used
  for piece 2, under sequential chain IDs.

Multiple pivots (V3.0)
----------------------
- --pivot accepts several residues separated by spaces, commas, or semicolons,
  for example A20,A40. The bends are applied in the listed order.
- Each bend acts on the full helix generated by the bend before it, so every
  pivot after the first must lie in the movable piece of the previous bend,
  i.e. after it along the helix axis. Bend k is built from pivot k's own local
  frame on that generated helix, so its phi, beta, tau, Sa, and Sr mean exactly
  what they mean for a single bend.
- phi, beta, tau, Sa, and Sr each take either one value, used at every pivot,
  or one value per pivot in pivot order, with the same separators.
- n pivots split the duplex into n + 1 pieces. Piece #1 comes from the input
  helix and piece #k + 1 from the helix generated by bend k; the output links
  these pieces and drops the unused part of every generated helix.

Assumptions
-----------
- The input has exactly two chains containing P atoms. Straight helices work
  automatically; already-bent helices should use --axis_range to define a local axis.
- The two strands have the same number of P-bearing residues.
- Splitting is determined from axial pairing, so selecting either residue of the
  same base pair gives the same split.
"""

