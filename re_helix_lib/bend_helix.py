@dataclass(frozen=True)
class BendTransform:
    """Pure rigid transform derived from one shift/phi/beta/tau candidate."""

    phi_deg: float
    beta_deg: float
    tau_deg: float
    shift_axial: float
    shift_radial: float
    shift_vector: Point3D
    pivot_shifted: Point3D
    shifted_radius: float
    hinge_point: Point3D
    hinge_dir: Point3D
    twist_axis_point_pre_align: Point3D
    twist_axis_point: Point3D
    twist_axis_dir: Point3D
    align_mode: str
    align_translation: Point3D

    def transform_coord(self, coord: Point3D) -> Point3D:
        """Apply the full-helix transform, including optional pivot alignment."""
        beta_rad = math.radians(self.beta_deg)
        tau_rad = math.radians(self.tau_deg)
        transformed = rotate_point_about_line(
            v_add(coord, self.shift_vector),
            self.hinge_point,
            self.hinge_dir,
            beta_rad,
        )
        if abs(tau_rad) > 0.0:
            transformed = rotate_point_about_line(
                transformed,
                self.twist_axis_point_pre_align,
                self.twist_axis_dir,
                tau_rad,
            )
        if self.align_mode == "y":
            transformed = v_add(transformed, self.align_translation)
        return transformed

    def transform_vector(self, vector: Point3D) -> Point3D:
        """Rotate a direction exactly as transform_coord rotates positions."""
        rotated = rotate_vector(vector, self.hinge_dir, math.radians(self.beta_deg))
        tau_rad = math.radians(self.tau_deg)
        if abs(tau_rad) > 0.0:
            rotated = rotate_vector(rotated, self.twist_axis_dir, tau_rad)
        return rotated

    # One bend also serves as a one-bend BendSequence, so screening resolvers
    # accept either.
    @property
    def transforms(self) -> Tuple["BendTransform", ...]:
        return (self,)

    def helix_coord(self, helix_index: int, coord: Point3D) -> Point3D:
        """Return an input coordinate on helix 0 (input) or helix 1 (this bend's)."""
        return self.transform_coord(coord) if helix_index else coord


@dataclass(frozen=True)
class BendSequence:
    """Chained bends in pivot order, with the full helix each one generates.

    Helix 0 is the input. Bend k acts on helix k - 1, the full helix bend k - 1
    generated, and generates helix k. ``preparations[k - 1]`` is pivot k's frame
    as it sits on helix k - 1.
    """

    preparations: Tuple[BendGeometryPreparation, ...]
    transforms: Tuple[BendTransform, ...]

    def helix_coord(self, helix_index: int, coord: Point3D) -> Point3D:
        """Return where an input coordinate sits on generated helix ``helix_index``."""
        for transform in self.transforms[:helix_index]:
            coord = transform.transform_coord(coord)
        return coord


